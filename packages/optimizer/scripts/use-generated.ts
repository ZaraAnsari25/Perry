// Copies an accepted generated interface into packages/agent-interface/generated/core.ts
// in the working tree, with a header naming the Droid session and date. Never commits.
//
// Usage: npm run use:generated [-- data/results/interface-gen-<time>.json]   (default: the newest accepted)

import { mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { GENERATED_INTERFACE_FILE, type InterfaceGenResult } from "../generate-interface.ts";

const repoPath = resolve(dirname(fileURLToPath(import.meta.url)), "../../..");
const resultsDir = join(repoPath, "data/results");
type Saved = Omit<InterfaceGenResult, "source"> & { sourceFile?: string };

const read = (rel: string) => JSON.parse(readFileSync(join(repoPath, rel), "utf8")) as Saved;
const requested = process.argv[2];
const file =
  requested ??
  readdirSync(resultsDir)
    .filter((f) => /^interface-gen-.*\.json$/.test(f))
    .map((f) => `data/results/${f}`)
    .filter((f) => read(f).status === "accepted")
    .sort()
    .at(-1);
if (!file) throw new Error("No accepted interface-gen result in data/results. Run npm run generate:interface first.");

const result = read(file);
if (result.status !== "accepted") throw new Error(`${file} was ${result.status}, not accepted.`);
if (!result.sourceFile) throw new Error(`${file} has no saved source file.`);

const header = [
  `// Generated by Factory Droid${result.droidSessionId ? ` (session ${result.droidSessionId})` : ""} on ${result.createdAt},`,
  `// accepted by Perry's gates: ${result.gates.map((g) => `${g.name} ${g.skipped ? "skipped" : g.ok ? "passed" : "failed"}`).join(", ")}.`,
  `// Result: ${file}. Don't edit by hand; regenerate with npm run generate:interface.`,
  "",
].join("\n");
const target = join(repoPath, GENERATED_INTERFACE_FILE);
mkdirSync(dirname(target), { recursive: true });
writeFileSync(target, header + readFileSync(join(repoPath, result.sourceFile), "utf8"));
console.log(`Copied ${result.sourceFile} to ${GENERATED_INTERFACE_FILE}. Review it, then commit it yourself.`);
console.log("Use it with PERRY_SHOP_IMPL=generated (sandbox and MCP server).");
